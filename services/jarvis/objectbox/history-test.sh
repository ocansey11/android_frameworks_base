#!/bin/bash
# Runs HistoryStoreTest: the service's History class (history/History.java)
# against a real ObjectBox store on the host, with stubs for android.util.Log
# and android.os.SystemProperties. Checks what is kept, its order, and that
# old conversations are forgotten.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$HERE/../java"
TOP="$(cd "$HERE/../../../../.." && pwd)"
JDK="${JAVA_HOME:-$TOP/prebuilts/jdk/jdk21/linux-x86}"
OBX="$TOP/vendor/jarvisos/prebuilts/objectbox"
JSON="${JSON_JAR:-$(find ~/.gradle/caches -name 'json-20240303.jar' | head -1)}"
[ -f "$JSON" ] || { echo "org.json jar not found; set JSON_JAR" >&2; exit 1; }
CP="$OBX/lib/java/objectbox-java-4.0.3.jar:$OBX/lib/java/objectbox-java-api-4.0.3.jar"
CP="$CP:$OBX/lib/java/essentials-3.1.0.jar:$OBX/objectbox-linux-4.0.3.jar:$JSON"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
SOURCES=$(cd "$SRC" && { grep -rl '^@Entity' --include='*.java' .; \
    grep -rl '^// Generated by objectbox/regenerate.sh' --include='*.java' .; } | sed "s#^#$SRC/#")
"$JDK/bin/javac" -nowarn -cp "$CP" -d "$WORK" $SOURCES \
    "$SRC/com/android/server/jarvis/core/JarvisStore.java" \
    "$SRC/com/android/server/jarvis/history/History.java" \
    $(find "$HERE/history-stubs" -name '*.java') "$HERE/HistoryStoreTest.java"
cd "$WORK"
"$JDK/bin/java" -cp "$WORK:$CP" HistoryStoreTest
